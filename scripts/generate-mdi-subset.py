"""Regenerate the subset Material Design Icons font and CSS.

Run after adding new ``mdi-*`` icons, or after upgrading Vuetify / @mdi/font::

    pip install fonttools brotli
    python scripts/generate-mdi-subset.py

The generated files are committed, so the normal frontend build needs no
Python tooling. Vuetify's own icon aliases are included in the scan because
many components render icons that never appear in this project's templates.
"""

from __future__ import annotations

import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
MDI_CSS = ROOT / "node_modules" / "@mdi" / "font" / "css" / "materialdesignicons.css"
MDI_TTF = (
    ROOT / "node_modules" / "@mdi" / "font" / "fonts" / "materialdesignicons-webfont.ttf"
)
VUETIFY_LIB = ROOT / "node_modules" / "vuetify" / "lib"
SRC = ROOT / "src"
OUT_FONT = ROOT / "src" / "assets" / "fonts" / "mdi-subset.woff2"
OUT_CSS = ROOT / "src" / "styles" / "mdi-subset.css"

ICON_RE = re.compile(r"mdi-[a-z0-9-]+")
SCAN_SUFFIXES = {".vue", ".ts", ".js", ".mjs"}

CSS_HEADER = """/* Generated by scripts/generate-mdi-subset.py. Do not edit by hand. */
@font-face {
  font-family: "Material Design Icons";
  src: url("../assets/fonts/mdi-subset.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.mdi:before,
.mdi-set {
  display: inline-block;
  font: normal normal normal 24px/1 "Material Design Icons";
  font-size: inherit;
  text-rendering: auto;
  line-height: inherit;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
"""


def collect_icons() -> list[str]:
    icons: set[str] = set()

    for root in (SRC, VUETIFY_LIB):
        if not root.exists():
            continue
        for path in root.rglob("*"):
            if not path.is_file() or path.suffix not in SCAN_SUFFIXES:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            icons.update(ICON_RE.findall(text))

    return sorted(icons)


def main() -> None:
    source_css = MDI_CSS.read_text(encoding="utf-8")
    icons = collect_icons()
    codepoints: list[int] = []
    rules: list[str] = []
    missing: list[str] = []

    for icon in icons:
        pattern = (
            r"\."
            + re.escape(icon)
            + r"::before\s*\{\s*content:\s*\"\\([0-9A-Fa-f]+)\";\s*\}"
        )
        match = re.search(pattern, source_css)
        if match is None:
            missing.append(icon)
            continue
        code = match.group(1).upper()
        codepoints.append(int(code, 16))
        rules.append(f'.{icon}::before {{ content: "\\{code}"; }}')

    font = TTFont(MDI_TTF)
    options = subset.Options()
    options.layout_features = ["*"]
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=codepoints)
    worker.subset(font)
    font.flavor = "woff2"

    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)
    font.save(OUT_FONT)
    OUT_CSS.write_text(
        CSS_HEADER + "\n" + "\n\n".join(rules) + "\n",
        encoding="utf-8",
    )

    print(f"icons found: {len(icons)}, rules generated: {len(rules)}")
    if missing:
        print(f"not present in @mdi/font: {', '.join(missing)}")
    print(f"font: {OUT_FONT.stat().st_size} bytes, css: {OUT_CSS.stat().st_size} bytes")


if __name__ == "__main__":
    main()
